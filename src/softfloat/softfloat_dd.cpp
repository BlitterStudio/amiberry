/*----------------------------------------------------------------------------
| double-double arithmetic (|lo| <= ulp(hi)/2 after every operation)
*----------------------------------------------------------------------------*/
static inline dd_t two_sum(double a, double b)
{
	const double s = a + b, bb = s - a;
	return { s, (a - (s - bb)) + (b - bb) };
}
static inline dd_t quick_two_sum(double a, double b) // |a| >= |b|
{
	const double s = a + b;
	return { s, b - (s - a) };
}
static inline dd_t two_prod(double a, double b)
{
	const double p = a * b;
	return { p, fma(a, b, -p) };
}
static inline dd_t dd_add(dd_t a, dd_t b)
{
	dd_t s = two_sum(a.hi, b.hi);
	const dd_t t = two_sum(a.lo, b.lo);
	s.lo += t.hi;
	s = quick_two_sum(s.hi, s.lo);
	s.lo += t.lo;
	return quick_two_sum(s.hi, s.lo);
}
// a + b where no cancellation can happen (same signs, or |b| well below |a|): one error-free sum
static inline dd_t dd_add_fast(dd_t a, dd_t b)
{
	dd_t s = two_sum(a.hi, b.hi);
	s.lo += a.lo + b.lo;
	return quick_two_sum(s.hi, s.lo);
}
static inline dd_t dd_add_d(dd_t a, double b)
{
	dd_t s = two_sum(a.hi, b);
	s.lo += a.lo;
	return quick_two_sum(s.hi, s.lo);
}
static inline dd_t dd_mul(dd_t a, dd_t b)
{
	dd_t p = two_prod(a.hi, b.hi);
	p.lo = fma(a.hi, b.lo, fma(a.lo, b.hi, p.lo));
	return quick_two_sum(p.hi, p.lo);
}
static inline dd_t dd_mul_d(dd_t a, double b)
{
	dd_t p = two_prod(a.hi, b);
	p.lo = fma(a.lo, b, p.lo);
	return quick_two_sum(p.hi, p.lo);
}
// a / b to about 2^-100: one division, the remainder with FMAs
static inline dd_t dd_div(dd_t a, dd_t b)
{
	const double inv = 1.0 / b.hi;
	const double q1 = a.hi * inv;
	// remainder a - q1 * b, exactly for the leading part
	const dd_t p = two_prod(q1, b.hi);
	double r = (a.hi - p.hi) - p.lo;
	r = r + a.lo - q1 * b.lo;
	const double q2 = r * inv;
	return quick_two_sum(q1, q2);
}
static inline dd_t dd_neg(dd_t a)
{
	return { -a.hi, -a.lo };
}

/*----------------------------------------------------------------------------
| conversions
*----------------------------------------------------------------------------*/
static inline double dd_pow2(int e) // 2^e, -1022 <= e <= 1023
{
	uint64_t b = (uint64_t)(e + 1023) << 52;
	double d;
	memcpy(&d, &b, sizeof d);
	return d;
}

static inline dd_t dd_scale(dd_t a, int e) // exact, |e| <= 1000 and no over/underflow
{
	const double f = dd_pow2(e);
	return { a.hi * f, a.lo * f };
}

// round to the nearest integer (ties to even), |v| < 2^51, without a library call
static inline double dd_round_int(double v)
{
	const double big = 6755399441055744.0; // 1.5 * 2^52
	return (v + big) - big;
}

// a normal extended value with |a| in [2^-900, 2^900] as an exact double-double
static inline dd_t dd_from_x80(floatx80 a)
{
	const int e = (a.high & 0x7fff) - 0x3fff;
	const double s = (a.high & 0x8000) ? -1.0 : 1.0;
	return { s * (double)(a.low >> 11) * dd_pow2(e - 52), s * (double)(a.low & 0x7ff) * dd_pow2(e - 63) };
}

/* Round z * 2^scale to the FPCR precision and rounding mode: z.hi normal,
 * |z.lo| <= ulp(z.hi). The 128-bit significand is exact (jammed below). */
static floatx80 dd_round_pack(dd_t z, int32_t scale, float_status *status)
{
	uint64_t hb, lb;
	memcpy(&hb, &z.hi, sizeof hb);
	memcpy(&lb, &z.lo, sizeof lb);
	const flag sign = hb >> 63;
	const int eh = (hb >> 52) & 0x7ff;
	unsigned __int128 s = (unsigned __int128)((hb & 0xfffffffffffffull) | (1ull << 52)) << 75;
	if (z.lo != 0) {
		int el = (lb >> 52) & 0x7ff;
		uint64_t ml = lb & 0xfffffffffffffull;
		if (el)
			ml |= 1ull << 52;
		else
			el = 1;
		const int shift = 75 - (eh - el);
		unsigned __int128 t;
		bool sticky = false;
		if (shift >= 0) {
			t = (unsigned __int128)ml << shift;
		} else if (shift > -64) {
			t = ml >> -shift;
			sticky = (ml & ((1ull << -shift) - 1)) != 0;
		} else {
			t = 0;
			sticky = true;
		}
		if ((lb >> 63) == sign) {
			s += t;
			s |= sticky;
		} else {
			s -= t + sticky;
			s |= sticky;
		}
	}
	int32_t zexp = eh - 1023 + 0x3fff + scale;
	if (!(s >> 127)) { // a power of two minus something
		s <<= 1;
		zexp--;
	}
	float_raise(float_flag_inexact, status);
	return roundAndPackFloatx80(status->floatx80_rounding_precision, sign, zexp, (uint64_t)(s >> 64), (uint64_t)s, status);
}

/* The host must round to nearest, without flush-to-zero; else the softfloat
 * functions are used (exact in any host mode). One FPCR read on AArch64. */
static inline bool dd_host_ok(void)
{
#if defined(__aarch64__)
	uint64_t fpcr;
	__asm__ volatile("mrs %0, fpcr" : "=r"(fpcr));
	return ((fpcr >> 22) & 7) == 0; // RMode round to nearest, FZ clear
#else
	return fegetround() == FE_TONEAREST;
#endif
}

// exponent and top 16 bits of the significand, as floatx80_make_compact() in softfloat_fpsp.cpp
static inline int32_t dd_compact(floatx80 a)
{
	return ((a.high & 0x7fff) << 16) | (uint32_t)(a.low >> 48);
}

// normal (integer bit set, not zero, denormal, infinity or NaN)
static inline bool dd_normal(floatx80 a)
{
	const int e = a.high & 0x7fff;
	return e != 0 && e != 0x7fff && (a.low >> 63);
}

/*----------------------------------------------------------------------------
| e^x = 2^m * T[j] * (1 + E), E = e^r - 1 with |r| <= ln2/128 (a little more:
| n is rounded from the high part only).
| x: |x| < 16384 ln2, exact.
*----------------------------------------------------------------------------*/
struct dd_exp_parts {
	dd_t t;  // 2^(j/64)
	dd_t e;  // e^r - 1
	int m;
	int n;
};

// e^r - 1 for |r| <= 0.0055: r and r^2/2 in double-double, the rest (< 2^-24 of the result) in double
static inline dd_t dd_expm1_small(dd_t r)
{
	const double rh = r.hi;
	dd_t r2 = two_prod(rh, rh);
	r2.lo = fma(2.0 * rh, r.lo, r2.lo);
	// tail = r^3 (1/3! + r/4! + ... + r^6/9!), Estrin's scheme for a short dependency chain
	const double q = r2.hi;
	const double p01 = fma(rh, dd_inv_fact4, dd_inv_fact3);
	const double p23 = fma(rh, dd_inv_fact6, dd_inv_fact5);
	const double p45 = fma(rh, dd_inv_fact8, dd_inv_fact7);
	const double p03 = fma(q, p23, p01);
	const double p46 = fma(q, dd_inv_fact9, p45);
	const double tail = q * rh * fma(q * q, p46, p03);
	const dd_t half = { r2.hi * 0.5, fma(r2.lo, 0.5, tail) };
	return dd_add_fast(r, half);
}

static inline void dd_exp_split(int n, dd_exp_parts *p)
{
	const int j = n & 63;
	p->t = dd_exp2_tbl[j];
	p->m = (n - j) / 64;
	p->n = n;
}

// x in natural units
static inline void dd_exp_reduce(dd_t x, dd_exp_parts *p)
{
	const double nd = dd_round_int(x.hi * dd_inv_ln2_64);
	// r = x - n ln2/64: n * piece 1 and n * piece 2 are exact, x.hi - n * piece 1 too
	// (Sterbenz), x.lo - n * piece 2 with an error-free sum
	const double h = fma(-nd, dd_ln2_64_1, x.hi);
	const dd_t l = two_sum(x.lo, -nd * dd_ln2_64_2);
	dd_t r = two_sum(h, l.hi);
	// n * piece 3 reaches 2^-51, beyond ulp(r.hi): renormalize, the polynomial
	// takes r^3 from r.hi alone
	r = quick_two_sum(r.hi, r.lo + fma(-nd, dd_ln2_64_3, l.lo));
	p->e = dd_expm1_small(r);
	dd_exp_split((int)nd, p);
}

// y in units of log2 (y = x / ln2): 2^y
static inline void dd_exp2_reduce(dd_t y, dd_exp_parts *p)
{
	const double nd = dd_round_int(y.hi * 64.0);
	dd_t f = two_sum(y.hi - nd * (1.0 / 64), y.lo); // exact
	p->e = dd_expm1_small(dd_mul(f, dd_ln2));
	dd_exp_split((int)nd, p);
}

// T * (1 + E), in [0.98, 2.03); |T E| < 0.006 T
static inline dd_t dd_exp_value(const dd_exp_parts *p)
{
	return dd_add_fast(p->t, dd_mul(p->t, p->e));
}

// e^|x| - 1 for normal 2^-65 <= |x| <= 70 ln2, relative error ~2^-100
static dd_t dd_expm1_abs(floatx80 a)
{
	dd_t x = dd_from_x80(a);
	if (x.hi < 0)
		x = dd_neg(x);
	dd_exp_parts p;
	dd_exp_reduce(x, &p);
	if (p.n == 0)
		return p.e;
	return dd_add_d(dd_scale(dd_exp_value(&p), p.m), -1.0);
}

