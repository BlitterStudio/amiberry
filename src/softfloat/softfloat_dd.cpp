/*============================================================================
 Fast extended-precision transcendental functions for the exact FPU core.

 The results are computed in double-double arithmetic (about 106 bits, with the
 host's fused multiply-add) and rounded once, with softfloat's
 roundAndPackFloatx80(), to the FPCR precision and rounding mode. The error
 before that rounding stays near 2^-70 of the result, so the results are within
 1 ulp and nearly always correctly rounded extended values: more accurate than
 the FPSP algorithms in softfloat_fpsp.cpp (which can be 2 ulp or more off) and
 3 to 7 times faster.

 Only the main range of each function is computed here: zeros, infinities,
 NaNs, denormals, unnormals, tiny arguments, the overflow and underflow
 ranges, exact results, sin/cos/tan of |x| >= 2^20 or very close to a multiple
 of pi/2 go to the softfloat_fpsp.cpp function, so the flags and special
 results there are unchanged.

 This needs round-to-nearest host arithmetic without flush-to-zero: each
 function checks it (dd_host_ok()) and else uses the softfloat function. The
 constants come from tools/gen_softfloat_dd_tables.py.
============================================================================*/

