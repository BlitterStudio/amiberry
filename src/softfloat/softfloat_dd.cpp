// log(1 + r) for |r| <= 0.0051: r and r^2/2 in double-double, the rest (< 2^-24 of the result) in double
static inline dd_t dd_log1p_small(dd_t r)
{
	const double rh = r.hi;
	dd_t r2 = two_prod(rh, rh);
	r2.lo = fma(2.0 * rh, r.lo, r2.lo);
	// tail = r^3 (1/3 - r/4 + r^2/5 - ... - r^8/11), Estrin's scheme
	const double q = r2.hi, q2 = q * q;
	const double p01 = fma(rh, -dd_inv_4, dd_inv_3);
	const double p23 = fma(rh, -dd_inv_6, dd_inv_5);
	const double p45 = fma(rh, -dd_inv_8, dd_inv_7);
	const double p67 = fma(rh, -dd_inv_10, dd_inv_9);
	const double p03 = fma(q, p23, p01);
	const double p47 = fma(q, p67, p45);
	const double p08 = fma(q2, fma(q2, -dd_inv_11, p47), p03);
	const double tail = q * rh * p08;
	const dd_t half = { -r2.hi * 0.5, fma(-r2.lo, 0.5, tail) };
	return dd_add_fast(r, half);
}

// k * ln2 as a double-double, |k| < 2^16
static inline dd_t dd_k_ln2(int k)
{
	const double kd = (double)k;
	dd_t r = two_sum(kd * dd_ln2_1, kd * dd_ln2_2); // kd * dd_ln2_1 is exact
	r.lo = fma(kd, dd_ln2_3, r.lo);
	return r;
}

/* log(2^k * m) for a double-double m in [1, 2). Arguments within 2^-8 of 1
 * (k = 0, or k = -1 and m close to 2) are taken as log1p(x - 1) directly. */
static dd_t dd_log_km(int k, dd_t m)
{
	if (k == 0 && m.hi < 1.0 + 1.0 / 256)
		return dd_log1p_small(two_sum(m.hi - 1.0, m.lo));
	if (k == -1 && m.hi >= 2.0 - 2.0 / 256) {
		const double h = m.hi * 0.5 - 1.0; // exact
		return dd_log1p_small(two_sum(h, m.lo * 0.5));
	}
	const int i = (int)((m.hi - 1.0) * 128.0);
	const double c = dd_log_inv[i];
	// r = m c - 1: m.hi c exactly, p.hi - 1 exact (Sterbenz)
	const dd_t p = two_prod(m.hi, c);
	const dd_t q = two_sum(p.lo, m.lo * c);
	dd_t r = two_sum(p.hi - 1.0, q.hi);
	r = quick_two_sum(r.hi, r.lo + q.lo);
	const dd_t l = dd_add(dd_log_neglog_inv[i], dd_log1p_small(r));
	return k ? dd_add(dd_k_ln2(k), l) : l;
}

// log of a positive normal extended value
static inline dd_t dd_log_x80(floatx80 a)
{
	const int k = (a.high & 0x7fff) - 0x3fff;
	const dd_t m = { (double)(a.low >> 11) * 0x1p-52, (double)(a.low & 0x7ff) * 0x1p-63 };
	return dd_log_km(k, m);
}

// log of a positive normal double-double
static inline dd_t dd_log_dd(dd_t z)
{
	uint64_t b;
	memcpy(&b, &z.hi, sizeof b);
	const int k = (int)((b >> 52) & 0x7ff) - 1023;
	const double f = dd_pow2(-k);
	// m.hi in [1, 2); m just below 1 (z.lo < 0) is in the near-1 path or table entry 0
	return dd_log_km(k, { z.hi * f, z.lo * f });
}

static inline bool dd_x80_is_one(floatx80 a)
{
	return (a.high & 0x7fff) == 0x3fff && a.low == 0x8000000000000000ull;
}

floatx80 floatx80_dd_logn(floatx80 a, float_status *status)
{
	if (!dd_normal(a) || !dd_host_ok() || (a.high & 0x8000) || dd_x80_is_one(a))
		return floatx80_logn(a, status);
	return dd_round_pack(dd_log_x80(a), 0, status);
}

floatx80 floatx80_dd_log2(floatx80 a, float_status *status)
{
	if (!dd_normal(a) || !dd_host_ok() || (a.high & 0x8000) || a.low == 0x8000000000000000ull) // a power of two: exact
		return floatx80_log2(a, status);
	return dd_round_pack(dd_mul(dd_log_x80(a), dd_inv_ln2), 0, status);
}

floatx80 floatx80_dd_log10(floatx80 a, float_status *status)
{
	if (!dd_normal(a) || !dd_host_ok() || (a.high & 0x8000))
		return floatx80_log10(a, status);
	const int e = (a.high & 0x7fff) - 0x3fff;
	if (e >= 0 && e <= 89) { // 10^0 .. 10^27 are exact, and so their log10
		const int j = (e * 1233) >> 12; // floor(e log10(2)): 10^j or 10^(j+1) has exponent e
		for (int jj = j; jj <= j + 1 && jj < 28; jj++) {
			if (dd_pow10[jj].exp == e && dd_pow10[jj].sig == a.low)
				return floatx80_log10(a, status);
		}
	}
	return dd_round_pack(dd_mul(dd_log_x80(a), dd_inv_ln10), 0, status);
}

floatx80 floatx80_dd_lognp1(floatx80 a, float_status *status)
{
	const int32_t c = dd_compact(a) & 0x7fffffff;
	const int e = (a.high & 0x7fff) - 0x3fff;
	if (!dd_normal(a) || !dd_host_ok() || c < 0x3FBE0000 || ((a.high & 0x8000) && e >= 0)) // tiny, x <= -1
		return floatx80_lognp1(a, status);
	if (e < -8) // |x| < 2^-8
		return dd_round_pack(dd_log1p_small(dd_from_x80(a)), 0, status);
	if (e >= 70) // 1 + x is x within 2^-70
		return dd_round_pack(dd_log_x80(a), 0, status);
	const dd_t x = dd_from_x80(a);
	const dd_t z = two_sum(1.0, x.hi); // 1 + x exactly (at most 71 bits)
	return dd_round_pack(dd_log_dd(quick_two_sum(z.hi, z.lo + x.lo)), 0, status);
}

floatx80 floatx80_dd_atanh(floatx80 a, float_status *status)
{
	const int32_t c = dd_compact(a) & 0x7fffffff;
	const int e = (a.high & 0x7fff) - 0x3fff;
	if (!dd_normal(a) || !dd_host_ok() || c < 0x3FD78000 || e >= 0) // 2^-40 <= |x| < 1
		return floatx80_atanh(a, status);
	const bool neg = (a.high & 0x8000) != 0;
	dd_t x = dd_from_x80(a);
	if (neg)
		x = dd_neg(x);
	dd_t r;
	if (e < -8) {
		// x + x^3/3 + x^5/5 + ..., the tail below 2^-24 of the result
		const double xh = x.hi, q = xh * xh, q2 = q * q;
		// 1/3 + q/5 + q^2/7 + q^3/9 + q^4/11
		const double p = fma(q2, fma(q2, dd_inv_11, fma(q, dd_inv_9, dd_inv_7)), fma(q, dd_inv_5, dd_inv_3));
		r = dd_add_d(x, q * xh * p);
	} else {
		// log1p(2x / (1 - x)) / 2
		const dd_t y = dd_div({ 2.0 * x.hi, 2.0 * x.lo }, dd_add_d(dd_neg(x), 1.0));
		r = dd_log_dd(dd_add_d(y, 1.0));
		r = { r.hi * 0.5, r.lo * 0.5 };
	}
	if (neg)
		r = dd_neg(r);
	return dd_round_pack(r, 0, status);
}

/*----------------------------------------------------------------------------
| trigonometric functions
*----------------------------------------------------------------------------*/

static inline dd_t dd_sqrt(dd_t a) // a > 0
{
	const double h = sqrt(a.hi);
	const dd_t p = two_prod(h, h);
	const double e = ((a.hi - p.hi) - p.lo + a.lo) / (2.0 * h);
	return quick_two_sum(h, e);
}

// sin t for |t| <= 1/128 (+): t - t^3/3! + ... + t^9/9!, the tail below 2^-23 of the result
static inline dd_t dd_sin_small(dd_t t)
{
	const double th = t.hi, q = th * th;
	const double p = fma(q, fma(q, fma(q, dd_inv_fact9, -dd_inv_fact7), dd_inv_fact5), -dd_inv_fact3);
	return dd_add_d(t, q * th * p);
}

// cos t for |t| <= 1/128 (+): 1 - t^2/2 + ... + t^8/8!
static inline dd_t dd_cos_small(dd_t t)
{
	const double th = t.hi;
	dd_t q = two_prod(th, th);
	q.lo = fma(2.0 * th, t.lo, q.lo);
	const double qh = q.hi;
	const double tail = qh * qh * fma(qh, fma(qh, dd_inv_fact8, -dd_inv_fact6), dd_inv_fact4);
	const dd_t one = { 1.0, 0.0 };
	return dd_add_fast(one, { -q.hi * 0.5, fma(-q.lo, 0.5, tail) });
}

/* x = k pi/2 + r, |r| <= pi/4 (a little more), for |x| < 2^20. False when r is
 * below 2^-30: x is too close to a multiple of pi/2 for this precision. */
static inline bool dd_trig_reduce(dd_t x, int *k, dd_t *r)
{
	const double kd = dd_round_int(x.hi * dd_two_over_pi.hi);
	// k * piece is exact (k < 2^20, pieces of 33 bits), x.hi - k * piece 1 too (Sterbenz)
	const double s = fma(-kd, dd_pio2_1, x.hi);
	const dd_t a = two_sum(s, x.lo);
	const dd_t b = two_sum(a.hi, -kd * dd_pio2_2);
	const dd_t c = two_sum(b.hi, -kd * dd_pio2_3);
	const double e = fma(-kd, dd_pio2_4, (a.lo + b.lo) + c.lo);
	*r = quick_two_sum(c.hi, e);
	*k = (int)kd;
	return fabs(r->hi) >= 0x1p-30;
}

// sin r and cos r for |r| <= 0.8: r = j/64 + t, |t| <= 1/128
static inline void dd_sincos_r(dd_t r, dd_t *sn, dd_t *cs)
{
	const double jd = dd_round_int(r.hi * 64.0);
	const dd_t t = two_sum(r.hi - jd * (1.0 / 64), r.lo); // r.hi - j/64 is exact
	const dd_t st = dd_sin_small(t), ct = dd_cos_small(t);
	if (jd == 0) {
		*sn = st;
		*cs = ct;
		return;
	}
	const int j = (int)fabs(jd);
	dd_t sa = dd_sin_tbl[j];
	const dd_t ca = dd_cos_tbl[j];
	if (jd < 0)
		sa = dd_neg(sa);
	*sn = dd_add(dd_mul(sa, ct), dd_mul(ca, st));
	*cs = dd_add(dd_mul(ca, ct), dd_neg(dd_mul(sa, st)));
}

// 2^-40 <= |x| < 2^20, normal
static inline bool dd_trig_arg(floatx80 a)
{
	const int32_t c = dd_compact(a) & 0x7fffffff;
	return dd_normal(a) && c >= 0x3FD78000 && (a.high & 0x7fff) < 0x3fff + 20 && dd_host_ok();
}

// sin and cos of x, false if the reduction is not accurate enough
static inline bool dd_sincos_x80(floatx80 a, dd_t *sn, dd_t *cs)
{
	int k;
	dd_t r, s, c;
	if (!dd_trig_reduce(dd_from_x80(a), &k, &r))
		return false;
	dd_sincos_r(r, &s, &c);
	switch (k & 3) {
	case 0: *sn = s; *cs = c; break;
	case 1: *sn = c; *cs = dd_neg(s); break;
	case 2: *sn = dd_neg(s); *cs = dd_neg(c); break;
	default: *sn = dd_neg(c); *cs = s; break;
	}
	return true;
}

floatx80 floatx80_dd_sin(floatx80 a, float_status *status)
{
	dd_t s, c;
	if (!dd_trig_arg(a) || !dd_sincos_x80(a, &s, &c))
		return floatx80_sin(a, status);
	return dd_round_pack(s, 0, status);
}

floatx80 floatx80_dd_cos(floatx80 a, float_status *status)
{
	dd_t s, c;
	if (!dd_trig_arg(a) || !dd_sincos_x80(a, &s, &c))
		return floatx80_cos(a, status);
	return dd_round_pack(c, 0, status);
}

floatx80 floatx80_dd_tan(floatx80 a, float_status *status)
{
	dd_t s, c;
	if (!dd_trig_arg(a) || !dd_sincos_x80(a, &s, &c))
		return floatx80_tan(a, status);
	return dd_round_pack(dd_div(s, c), 0, status);
}

// sin to the return value, cos to *c, as floatx80_sincos()
floatx80 floatx80_dd_sincos(floatx80 a, floatx80 *c, float_status *status)
{
	dd_t sn, cs;
	if (!dd_trig_arg(a) || !dd_sincos_x80(a, &sn, &cs))
		return floatx80_sincos(a, c, status);
	*c = dd_round_pack(cs, 0, status);
	return dd_round_pack(sn, 0, status);
}

/*----------------------------------------------------------------------------
| inverse trigonometric functions
*----------------------------------------------------------------------------*/

// atan y for y > 0 (normal double-double, below 2^1000)
static dd_t dd_atan_pos(dd_t y)
{
	const bool inv = y.hi > 1.0;
	if (inv) {
		const dd_t one = { 1.0, 0.0 };
		y = dd_div(one, y);
	}
	// y in (0, 1]: atan y = atan(j/64) + atan u, u = (y - j/64) / (1 + y j/64), |u| <= 1/128 (+)
	const double jd = dd_round_int(y.hi * 64.0);
	dd_t u = y;
	if (jd != 0) {
		const double cj = jd * (1.0 / 64);
		const dd_t num = two_sum(y.hi - cj, y.lo); // y.hi - j/64 is exact
		u = dd_div(num, dd_add_d(dd_mul_d(y, cj), 1.0));
	}
	// u - u^3/3 + u^5/5 - ... - u^11/11, the tail below 2^-23 of the result
	const double uh = u.hi, q = uh * uh, q2 = q * q;
	const double p = fma(q2, fma(q2, -dd_inv_11, fma(q, dd_inv_9, -dd_inv_7)), fma(q, dd_inv_5, -dd_inv_3));
	dd_t r = dd_add_d(u, q * uh * p);
	if (jd != 0)
		r = dd_add(dd_atan_tbl[(int)jd], r);
	if (inv)
		r = dd_add(dd_pio2, dd_neg(r));
	return r;
}

floatx80 floatx80_dd_atan(floatx80 a, float_status *status)
{
	const int32_t c = dd_compact(a) & 0x7fffffff;
	if (!dd_normal(a) || !dd_host_ok() || c < 0x3FD78000 || (a.high & 0x7fff) >= 0x3fff + 900) // 2^-40 <= |x| < 2^900
		return floatx80_atan(a, status);
	const bool neg = (a.high & 0x8000) != 0;
	dd_t x = dd_from_x80(a);
	if (neg)
		x = dd_neg(x);
	dd_t r = dd_atan_pos(x);
	if (neg)
		r = dd_neg(r);
	return dd_round_pack(r, 0, status);
}

floatx80 floatx80_dd_asin(floatx80 a, float_status *status)
{
	const int32_t c = dd_compact(a) & 0x7fffffff;
	if (!dd_normal(a) || !dd_host_ok() || c < 0x3FD78000 || (a.high & 0x7fff) >= 0x3fff) // 2^-40 <= |x| < 1
		return floatx80_asin(a, status);
	const bool neg = (a.high & 0x8000) != 0;
	dd_t x = dd_from_x80(a);
	if (neg)
		x = dd_neg(x);
	// asin x = atan(x / sqrt((1 - x)(1 + x)))
	const dd_t d = dd_mul(dd_add_d(dd_neg(x), 1.0), dd_add_d(x, 1.0));
	dd_t r = dd_atan_pos(dd_div(x, dd_sqrt(d)));
	if (neg)
		r = dd_neg(r);
	return dd_round_pack(r, 0, status);
}

floatx80 floatx80_dd_acos(floatx80 a, float_status *status)
{
	const int32_t c = dd_compact(a) & 0x7fffffff;
	if (!dd_normal(a) || !dd_host_ok() || c < 0x3FD78000 || (a.high & 0x7fff) >= 0x3fff) // 2^-40 <= |x| < 1
		return floatx80_acos(a, status);
	// acos x = 2 atan(sqrt((1 - x) / (1 + x)))
	const dd_t x = dd_from_x80(a);
	const dd_t t = dd_sqrt(dd_div(dd_add_d(dd_neg(x), 1.0), dd_add_d(x, 1.0)));
	const dd_t r = dd_atan_pos(t);
	return dd_round_pack({ r.hi * 2.0, r.lo * 2.0 }, 0, status);
}

