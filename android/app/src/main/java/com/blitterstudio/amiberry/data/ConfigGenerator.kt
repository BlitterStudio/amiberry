package com.blitterstudio.amiberry.data

import android.content.Context
import com.blitterstudio.amiberry.data.model.AcceleratorJumpers
import com.blitterstudio.amiberry.data.model.CustomControls
import com.blitterstudio.amiberry.data.model.StoragePaths
import com.blitterstudio.amiberry.data.model.EmulatorSettings
import com.blitterstudio.amiberry.data.model.SettingsBoards
import com.blitterstudio.amiberry.data.model.SettingsSchema
import java.io.File

/**
 * Generates .uae config files from EmulatorSettings.
 * Config key names match cfgfile_save_options() format in cfgfile.cpp.
 */
object ConfigGenerator {
	internal val transientConfigFileNames = setOf(
		".android_controls.uae",
		".current_settings.uae",
		".intent_quickstart_settings.uae",
		".last_session.uae",
		".quickstart_settings.uae",
		AdvancedLaunchActions.SETTINGS_ADVANCED_CONFIG
	)

	fun generate(settings: EmulatorSettings): String {
		val sb = StringBuilder()
		sb.appendLine("; Generated by Amiberry Android UI")
		sb.appendLine()

		// The preset and compatibility level the settings were made from, so
		// the Settings screen reads the same model back.
		sb.appendLine("amiberry.android_preset=${settings.baseModel.cmdArg}:${settings.baseConfig}:${settings.baseLevel}")

		// CPU. Every value is written, zero included, so the file is the
		// whole machine (with the options below).
		sb.appendLine("cpu_model=${settings.cpuModel}")
		sb.appendLine("cpu_compatible=${settings.cpuCompatible.toCfg()}")
		sb.appendLine("cpu_24bit_addressing=${settings.address24Bit.toCfg()}")
		sb.appendLine("cpu_speed=${settings.cpuSpeed}")
		sb.appendLine("fpu_model=${settings.fpuModel}")
		sb.appendLine("cachesize=${settings.jitCacheSize}")
		sb.appendLine("compfpu=${settings.jitFpu.toCfg()}")

		// Chipset
		sb.appendLine("chipset=${settings.chipset}")
		sb.appendLine("immediate_blits=${settings.immediateBlits.toCfg()}")
		sb.appendLine("collision_level=${settings.collisionLevel}")
		sb.appendLine("cycle_exact=${settings.cycleExact}")
		sb.appendLine("ntsc=${settings.ntsc.toCfg()}")

		// Memory
		sb.appendLine("chipmem_size=${settings.chipRam}")
		sb.appendLine("bogomem_size=${settings.slowRam}")
		sb.appendLine("fastmem_size=${settings.fastRam}")
		sb.appendLine("z3mem_size=${settings.z3Ram}")

		// ROM
		if (settings.romFile.isNotEmpty()) {
			sb.appendLine("kickstart_rom_file=${settings.romFile}")
		}
		if (settings.romExtFile.isNotEmpty()) {
			sb.appendLine("kickstart_ext_rom_file=${settings.romExtFile}")
		}

		// Floppy drives
		sb.appendLine("floppy0=${settings.floppy0}")
		sb.appendLine("floppy0type=${settings.floppy0Type}")
		sb.appendLine("floppy1=${settings.floppy1}")
		sb.appendLine("floppy1type=${settings.floppy1Type}")
		sb.appendLine("floppy2=${settings.floppy2}")
		sb.appendLine("floppy2type=${settings.floppy2Type}")
		sb.appendLine("floppy3=${settings.floppy3}")
		sb.appendLine("floppy3type=${settings.floppy3Type}")
		sb.appendLine("floppy0sound=${settings.floppy0Sound}")
		sb.appendLine("floppy1sound=${settings.floppy1Sound}")
		sb.appendLine("floppy2sound=${settings.floppy2Sound}")
		sb.appendLine("floppy3sound=${settings.floppy3Sound}")
		sb.appendLine("floppy0soundvolume_disk=${settings.floppy0SoundVolumeDisk}")
		sb.appendLine("floppy1soundvolume_disk=${settings.floppy1SoundVolumeDisk}")
		sb.appendLine("floppy2soundvolume_disk=${settings.floppy2SoundVolumeDisk}")
		sb.appendLine("floppy3soundvolume_disk=${settings.floppy3SoundVolumeDisk}")
		sb.appendLine("floppy0soundvolume_empty=${settings.floppy0SoundVolumeEmpty}")
		sb.appendLine("floppy1soundvolume_empty=${settings.floppy1SoundVolumeEmpty}")
		sb.appendLine("floppy2soundvolume_empty=${settings.floppy2SoundVolumeEmpty}")
		sb.appendLine("floppy3soundvolume_empty=${settings.floppy3SoundVolumeEmpty}")

		// CD
		if (settings.cdImage.isNotEmpty()) {
			sb.appendLine("cdimage0=${settings.cdImage}")
		}

		// Hard drives (hardfiles on the UAE controller)
		settings.hardDrives.forEachIndexed { index, hd ->
			if (hd.path.isNotEmpty()) {
				val access = if (hd.readOnly) "ro" else "rw"
				sb.appendLine("hardfile2=$access,:${hd.path},0,0,0,512,${hd.bootPriority},,uae$index")
			}
		}

		// Expansion boards: the units' own lines (SettingsBoards), each
		// unit's options after its entry, as the reader needs it
		// (cfgfile_read_board_rom creates the entry from the _rom_file line
		// and reads _rom_options with the entry in hand, cfgfile.cpp:6380).
		SettingsSchema.current?.let { schema ->
			SettingsBoards.render(schema, settings.boards).forEach(sb::appendLine)
		}
		// The accelerator's board and its jumpers, in the writer's order:
		// the packed jumpers line is read against the board the file has
		// selected so far (cfgfile.cpp:7077-7082), so the type comes first.
		SettingsSchema.current?.let { schema ->
			val type = settings.optionValue("cpuboard_type") ?: "none"
			if (type != "none") {
				sb.appendLine("cpuboard_type=$type")
				val board = schema.acceleratorBoard(type)
				if (board != null) {
					val packed = AcceleratorJumpers.pack(board, settings.acceleratorJumpers)
					if (packed.isNotEmpty()) sb.appendLine("cpuboard_settings=$packed")
				}
			}
		}

		// Sound
		sb.appendLine("sound_output=${settings.soundOutput}")
		sb.appendLine("sound_frequency=${settings.soundFreq}")
		sb.appendLine("sound_max_buff=${settings.soundBuffer}")
		sb.appendLine("sound_channels=${settings.soundChannels}")
		// Attenuation, as the emulator stores volumes: 0 is full volume.
		sb.appendLine("sound_volume=${settings.soundVolume}")
		sb.appendLine("sound_volume_paula=${settings.soundVolumePaula}")
		sb.appendLine("sound_volume_cd=${settings.soundVolumeCd}")
		sb.appendLine("sound_volume_ahi=${settings.soundVolumeAhi}")
		sb.appendLine("sound_volume_midi=${settings.soundVolumeMidi}")

		// Display
		sb.appendLine("gfx_width=${settings.gfxWidth}")
		sb.appendLine("gfx_height=${settings.gfxHeight}")
		// An integer option: the emulator reads "true" as 0 (aspect correction off).
		sb.appendLine("amiberry.gfx_correct_aspect=${if (settings.correctAspect) "1" else "0"}")
		sb.appendLine("amiberry.gfx_auto_crop=${settings.autoCrop.toCfg()}")
		// Amiberry target option: the native parser only accepts the prefixed form.
		sb.appendLine("amiberry.scaling_method=${settings.scalingMethod}")
		sb.appendLine("gfx_autoresolution=${settings.gfxAutoresolution}")
		sb.appendLine("amiberry.shader=${settings.shader}")

		// Input
		sb.appendLine("joyport0=${settings.joyport0}")
		// When on-screen joystick is selected for port 1, omit joyport1 from config
		// and let on_screen_joystick_set_enabled() auto-assign it at runtime
		if (settings.joyport1 != "onscreen_joy") {
			sb.appendLine("joyport1=${settings.joyport1}")
		}
		// Persist the Android UI's joyport1 choice for reliable round-trip parsing
		sb.appendLine("amiberry.android_joyport1=${settings.joyport1}")
		// Analog stick mouse map — always explicit so the disabled state
		// round-trips and is not overridden by remembered-control fallback
		sb.appendLine("joyport0mousemap=${if (settings.joyport0MouseMap) "1" else "0"}")
		sb.appendLine("joyport1mousemap=${if (settings.joyport1MouseMap) "1" else "0"}")
		sb.appendLine("input.joymouse_speed_analog=${settings.analogMouseSpeed}")

		appendCustomControls(sb, settings)

		// Amiberry-specific
		sb.appendLine("amiberry.onscreen_joystick=${settings.onScreenJoystick.toCfg()}")
		sb.appendLine("amiberry.vkbd_enabled=${settings.onScreenKeyboardAvailable.toCfg()}")
		sb.appendLine("amiberry.vkbd_touch_button=${settings.onScreenKeyboardButton.toCfg()}")
		sb.appendLine("amiberry.vkbd_numpad=${settings.onScreenKeyboardNumpad.toCfg()}")
		// Always explicit: null ("Default") serializes as the reset sentinel so a
		// remembered toggle cannot replace the saved default choice on reload.
		// "" (explicitly disabled) and button names round-trip unchanged.
		sb.appendLine("amiberry.vkbd_toggle=${settings.onScreenKeyboardToggle ?: "default"}")
		sb.appendLine("input.default_osk=${settings.onScreenKeyboardAvailable.toCfg()}")

		// The schema options without a field (the rest of the preset's machine
		// and options a configuration had), in the layer's order: after the
		// fields, so a chipset extra loads after the CPU it depends on.
		// cpuboard_type is written with its jumpers above (the reader needs
		// the board before the packed line).
		optionsInLayerOrder(settings.options - "cpuboard_type").forEach { (id, value) -> sb.appendLine("$id=$value") }

		// Skip GUI when launched from Android native UI
		sb.appendLine("use_gui=no")

		return sb.toString()
	}

	fun generateControlConfig(settings: EmulatorSettings): String {
		val sb = StringBuilder()
		sb.appendLine("; Generated by Amiberry Android UI")
		sb.appendLine()

		sb.appendLine("amiberry.shader=${settings.shader}")
		sb.appendLine("joyport0=${settings.joyport0}")
		if (settings.joyport1 != "onscreen_joy") {
			sb.appendLine("joyport1=${settings.joyport1}")
		}
		sb.appendLine("amiberry.android_joyport1=${settings.joyport1}")
		// Analog stick mouse map — always explicit so the disabled state
		// round-trips and is not overridden by remembered-control fallback
		sb.appendLine("joyport0mousemap=${if (settings.joyport0MouseMap) "1" else "0"}")
		sb.appendLine("joyport1mousemap=${if (settings.joyport1MouseMap) "1" else "0"}")
		sb.appendLine("input.joymouse_speed_analog=${settings.analogMouseSpeed}")
		appendCustomControls(sb, settings)
		sb.appendLine("amiberry.onscreen_joystick=${settings.onScreenJoystick.toCfg()}")
		sb.appendLine("amiberry.vkbd_enabled=${settings.onScreenKeyboardAvailable.toCfg()}")
		sb.appendLine("amiberry.vkbd_touch_button=${settings.onScreenKeyboardButton.toCfg()}")
		sb.appendLine("amiberry.vkbd_numpad=${settings.onScreenKeyboardNumpad.toCfg()}")
		// Always explicit: null ("Default") serializes as the reset sentinel so a
		// remembered toggle cannot replace the saved default choice on reload.
		// "" (explicitly disabled) and button names round-trip unchanged.
		sb.appendLine("amiberry.vkbd_toggle=${settings.onScreenKeyboardToggle ?: "default"}")
		sb.appendLine("input.default_osk=${settings.onScreenKeyboardAvailable.toCfg()}")
		sb.appendLine("use_gui=no")

		return sb.toString()
	}

	/**
	 * The custom controls (CustomControls), after the joyport lines they
	 * apply to (load_custom_options reads the port's device,
	 * amiberry_input.cpp:1820-1825). The writer spells every control of a
	 * joystick port, an empty value included (cfgfile.cpp:2847-2880): the
	 * reader applies an empty line as the slot's default (custom_event_of,
	 * amiberry_input.cpp:1790), so an earlier binding of the port does not
	 * survive a control set back to Default. A full configuration and the
	 * WHDLoad launch's control configuration both carry them.
	 */
	private fun appendCustomControls(sb: StringBuilder, settings: EmulatorSettings) {
		val schema = SettingsSchema.current ?: return
		val keys = settings.customControls.mappings.keys
		for (port in keys.map { it.port }.distinct().sorted()) {
			for (hotkey in listOf(false, true)) {
				if (keys.none { it.port == port && it.hotkey == hotkey }) continue
				for (control in schema.customControls) {
					val key = CustomControls.Key(port, hotkey, control.axis, control.id)
					sb.appendLine("${key.id}=${settings.customControls.event(key)}")
				}
			}
		}
	}

	fun writeConfig(context: Context, settings: EmulatorSettings, filename: String): File {
		val file = configFile(context, filename)
		file.writeText(generate(settings))
		return file
	}

	fun writeControlConfig(context: Context, settings: EmulatorSettings, filename: String): File {
		val file = configFile(context, filename)
		file.writeText(generateControlConfig(settings))
		return file
	}

	internal fun configFile(context: Context, filename: String): File {
		val confDir = configDirectoryFor(context.getExternalFilesDir(null), context.noBackupFilesDir, filename)
		if (!confDir.exists()) confDir.mkdirs()
		return File(confDir, filename)
	}

	internal fun legacyExternalConfigFile(context: Context, filename: String): File =
		File(File(context.getExternalFilesDir(null), StoragePaths.CONFIGURATIONS), filename)

	internal fun configDirectoryFor(externalFilesDir: File?, noBackupFilesDir: File, filename: String): File {
		val baseDir = if (filename in transientConfigFileNames) {
			noBackupFilesDir
		} else {
			externalFilesDir ?: noBackupFilesDir
		}
		return File(baseDir, StoragePaths.CONFIGURATIONS)
	}

	/** [options] in the order the settings layer lists them (the schema's); others after, by ID. */
	private fun optionsInLayerOrder(options: Map<String, String>): List<Pair<String, String>> {
		val order = SettingsSchema.current?.options?.keys.orEmpty()
		val listed = order.mapNotNull { id -> options[id]?.let { id to it } }
		val rest = options.filterKeys { it !in order }.toSortedMap().toList()
		return listed + rest
	}

	private fun Boolean.toCfg(): String = if (this) "true" else "false"
}
