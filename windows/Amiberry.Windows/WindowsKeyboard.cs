namespace Amiberry.Windows;

internal static class WindowsKeyboard
{
    // Windows exposes Set 1 scan codes. E0 distinguishes the navigation block,
    // keypad Enter/divide, and the right-hand modifiers from their base keys.
    public static uint Usage(uint scanCode, bool extended, bool pause)
    {
        if (pause) return 72; // Pause has an E1 sequence, which PhysicalKeyStatus does not expose.
        if (extended)
            return scanCode switch
            {
                0x1C => 88, 0x1D => 0xE4, 0x35 => 84, 0x37 => 70, 0x38 => 0xE6,
                0x45 => 83, 0x47 => 74, 0x48 => 82, 0x49 => 75, 0x4B => 80,
                0x4D => 79, 0x4F => 77, 0x50 => 81, 0x51 => 78, 0x52 => 73,
                0x53 => 76, 0x5B => 0xE3, 0x5C => 0xE7, 0x5D => 101,
                0x20 => 127, 0x2E => 129, 0x30 => 128, _ => 0
            };
        if (scanCode is >= 0x02 and <= 0x0B) return scanCode - 0x02 + 30;
        if (scanCode is >= 0x3B and <= 0x44) return scanCode - 0x3B + 58;
        if (scanCode is >= 0x64 and <= 0x6E) return scanCode - 0x64 + 104;
        return scanCode switch
        {
            0x01 => 41, 0x0C => 45, 0x0D => 46, 0x0E => 42, 0x0F => 43,
            0x10 => 20, 0x11 => 26, 0x12 => 8, 0x13 => 21, 0x14 => 23,
            0x15 => 28, 0x16 => 24, 0x17 => 12, 0x18 => 18, 0x19 => 19,
            0x1A => 47, 0x1B => 48, 0x1C => 40, 0x1D => 0xE0,
            0x1E => 4, 0x1F => 22, 0x20 => 7, 0x21 => 9, 0x22 => 10,
            0x23 => 11, 0x24 => 13, 0x25 => 14, 0x26 => 15, 0x27 => 51,
            0x28 => 52, 0x29 => 53, 0x2A => 0xE1, 0x2B => 49,
            0x2C => 29, 0x2D => 27, 0x2E => 6, 0x2F => 25, 0x30 => 5,
            0x31 => 17, 0x32 => 16, 0x33 => 54, 0x34 => 55, 0x35 => 56,
            0x36 => 0xE5, 0x37 => 85, 0x38 => 0xE2, 0x39 => 44, 0x3A => 57,
            0x45 => 83, 0x46 => 71, 0x47 => 95, 0x48 => 96, 0x49 => 97,
            0x4A => 86, 0x4B => 92, 0x4C => 93, 0x4D => 94, 0x4E => 87,
            0x4F => 89, 0x50 => 90, 0x51 => 91, 0x52 => 98, 0x53 => 99,
            0x56 => 100, 0x57 => 68, 0x58 => 69, 0x76 => 115, _ => 0
        };
    }

    public static uint Modifier(uint usage) => usage switch
    {
        0xE0 => 0x01, 0xE4 => 0x02, 0xE1 => 0x04, 0xE5 => 0x08,
        0xE2 => 0x10, 0xE6 => 0x20, 0xE3 => 0x40, 0xE7 => 0x80, _ => 0
    };
}
