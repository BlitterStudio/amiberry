#!/usr/bin/env python3
"""Constants for src/softfloat/softfloat_dd.cpp (double-double transcendentals).

Prints C++ definitions: every constant as a pair of doubles (hi + lo, |lo| <= ulp(hi)/2),
computed with Python's decimal module at 60 significant digits, and ln2/64 split into
pieces whose product with an integer up to 2^21 is exact.

usage: python3 tools/gen_softfloat_dd_tables.py > /tmp/tables.inc
"""
from decimal import Decimal, getcontext
from fractions import Fraction
import math

getcontext().prec = 60
LN2 = Decimal(2).ln()
LN10 = Decimal(10).ln()


def dd(v):
    hi = float(v)                       # correctly rounded
    lo = float(v - Decimal(hi))
    return hi, lo


def chop(v, bits):
    """v truncated to `bits` significant bits, as an exact double"""
    f = Fraction(v)
    e = math.floor(math.log2(abs(f)))
    scale = Fraction(2) ** (bits - 1 - e)
    return float(Fraction(math.floor(f * scale)) / scale)


def hexd(x):
    return x.hex()


def main():
    print("// generated by tools/gen_softfloat_dd_tables.py, do not edit")
    print("static const dd_t dd_exp2_tbl[64] = {")
    for j in range(64):
        hi, lo = dd((LN2 * j / 64).exp())
        print(f"\t{{ {hexd(hi)}, {hexd(lo)} }}, // 2^({j}/64)")
    print("};")
    l = LN2 / 64
    c1 = chop(l, 32)
    c2 = chop(l - Decimal(c1), 32)
    c3 = float(l - Decimal(c1) - Decimal(c2))
    print(f"static const double dd_ln2_64_1 = {hexd(c1)}; // ln2/64: 32 bits")
    print(f"static const double dd_ln2_64_2 = {hexd(c2)}; // next 32 bits")
    print(f"static const double dd_ln2_64_3 = {hexd(c3)}; // rest")
    print(f"static const double dd_inv_ln2_64 = {hexd(float(64 / LN2))}; // 64/ln2 (estimate only)")
    for name, v in (("ln2", LN2), ("ln10", LN10), ("log2_10", LN10 / LN2)):
        hi, lo = dd(v)
        print(f"static const dd_t dd_{name} = {{ {hexd(hi)}, {hexd(lo)} }};")
    # 1/k! for the exp polynomial tail
    for k in range(3, 10):
        print(f"static const double dd_inv_fact{k} = {hexd(float(Decimal(1) / math.factorial(k)))};")
    # log: m in [1, 2) in 128 intervals; c = 1/(interval centre) to 9 significant bits,
    # -log(c) as a double-double; m * c - 1 stays within about +-2^-8
    print("static const double dd_log_inv[128] = {")
    invs = []
    for i in range(128):
        centre = Fraction(1) + Fraction(2 * i + 1, 256)
        c = 1 / centre
        e = math.floor(math.log2(c))
        q = Fraction(round(c * 2 ** (8 - e))) / 2 ** (8 - e)  # 9 bits
        invs.append(q)
        print(f"\t{hexd(float(q))},")
    print("};")
    print("static const dd_t dd_log_neglog_inv[128] = {")
    for q in invs:
        hi, lo = dd(-(Decimal(q.numerator) / Decimal(q.denominator)).ln())
        print(f"\t{{ {hexd(hi)}, {hexd(lo)} }},")
    print("};")
    for name, v in (("inv_ln2", 1 / LN2), ("inv_ln10", 1 / LN10), ("log10_2", LN2 / LN10)):
        hi, lo = dd(v)
        print(f"static const dd_t dd_{name} = {{ {hexd(hi)}, {hexd(lo)} }};")
    # ln2 in pieces: k * piece 1 exact for |k| < 2^16
    l1 = chop(LN2, 36)
    l2 = float(LN2 - Decimal(l1))
    l3 = float(LN2 - Decimal(l1) - Decimal(l2))
    print(f"static const double dd_ln2_1 = {hexd(l1)}; // 36 bits")
    print(f"static const double dd_ln2_2 = {hexd(l2)};")
    print(f"static const double dd_ln2_3 = {hexd(l3)};")
    # the powers of ten that are exact extended values (10^0 .. 10^27): log10 of them is exact
    print("static const struct { int exp; uint64_t sig; } dd_pow10[28] = {")
    for j in range(28):
        f = 5 ** j  # 10^j = 5^j * 2^j, 5^27 has 63 bits
        b = f.bit_length()
        print(f"\t{{ {j + b - 1}, 0x{f << (64 - b):016x}ull }}, // 10^{j}")
    print("};")
    # trigonometric functions: pi/2 in pieces for the reduction (k * piece exact for |k| < 2^20)
    getcontext().prec = 80
    pi = Decimal(0)
    # Machin: pi = 16 atan(1/5) - 4 atan(1/239)
    def atan_inv(n):
        x = Decimal(1) / n
        total, term, k, x2 = Decimal(0), x, 1, x * x
        while abs(term) > Decimal(10) ** -78:
            total += term / k if (k // 2) % 2 == 0 else -term / k
            term *= x2
            k += 2
        return total
    pi = 16 * atan_inv(5) - 4 * atan_inv(239)
    half_pi = pi / 2
    rest = half_pi
    pieces = []
    for _ in range(3):
        c = chop(rest, 33)
        pieces.append(c)
        rest -= Decimal(c)
    pieces.append(float(rest))
    for i, c in enumerate(pieces):
        print(f"static const double dd_pio2_{i + 1} = {hexd(c)};")
    for name, v in (("pio2", half_pi), ("pi", pi), ("two_over_pi", 2 / pi)):
        hi, lo = dd(v)
        print(f"static const dd_t dd_{name} = {{ {hexd(hi)}, {hexd(lo)} }};")

    def sin_d(x):
        total, term, k = Decimal(0), x, 1
        while abs(term) > Decimal(10) ** -78:
            total += term
            term *= -x * x / ((k + 1) * (k + 2))
            k += 2
        return total

    def cos_d(x):
        total, term, k = Decimal(0), Decimal(1), 0
        while abs(term) > Decimal(10) ** -78:
            total += term
            term *= -x * x / ((k + 1) * (k + 2))
            k += 2
        return total

    def atan_d(x):
        # atan x = 2 atan(x / (1 + sqrt(1 + x^2))) until small, then the series
        n = 0
        while abs(x) > Decimal("0.1"):
            x = x / (1 + (1 + x * x).sqrt())
            n += 1
        total, term, k, x2 = Decimal(0), x, 1, x * x
        while abs(term) > Decimal(10) ** -78:
            total += term / k if (k // 2) % 2 == 0 else -term / k
            term *= x2
            k += 2
        return total * (2 ** n)
    print("static const dd_t dd_sin_tbl[53] = { // sin(j/64)")
    for j in range(53):
        hi, lo = dd(sin_d(Decimal(j) / 64))
        print(f"\t{{ {hexd(hi)}, {hexd(lo)} }},")
    print("};")
    print("static const dd_t dd_cos_tbl[53] = { // cos(j/64)")
    for j in range(53):
        hi, lo = dd(cos_d(Decimal(j) / 64))
        print(f"\t{{ {hexd(hi)}, {hexd(lo)} }},")
    print("};")
    print("static const dd_t dd_atan_tbl[65] = { // atan(j/64)")
    for j in range(65):
        hi, lo = dd(atan_d(Decimal(j) / 64))
        print(f"\t{{ {hexd(hi)}, {hexd(lo)} }},")
    print("};")
    getcontext().prec = 60
    # 1/k for the log1p series tail (r^3/3 ...)
    for k in range(3, 12):
        print(f"static const double dd_inv_{k} = {hexd(float(Decimal(1) / k))};")


if __name__ == "__main__":
    main()
